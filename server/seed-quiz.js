function validateQuizData(data) {
  if (data.questions.length !== 75) {
    throw new Error(`Expected 75 questions, found ${data.questions.length}.`);
  }

  data.questions.forEach((question, index) => {
    if (!question.prompt || !Array.isArray(question.options) || question.options.length !== 4) {
      throw new Error(`Question ${index + 1} must have a prompt and exactly 4 options.`);
    }

    if (!Number.isInteger(question.answer) || question.answer < 0 || question.answer >= question.options.length) {
      throw new Error(`Question ${index + 1} has an invalid answer index.`);
    }
  });
}

async function seedQuiz() {
  validateQuizData(quizData);

  if (!process.env.MONGO_URI) {
    throw new Error('MONGO_URI is missing. Add it to .env before running this seed script.');
  }

  await mongoose.connect(process.env.MONGO_URI);
  const quiz = await Quiz.findOneAndUpdate(
    { courseCode: quizData.courseCode, title: quizData.title },
    { $set: quizData },
    { new: true, upsert: true, runValidators: true, setDefaultsOnInsert: true }
  );

  console.log(`Seeded quiz "${quiz.title}" with ${quiz.questions.length} questions.`);
  console.log(`Quiz id: ${quiz._id}`);
}

if (require.main === module) {
  seedQuiz()
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    })
    .finally(async () => {
      await mongoose.disconnect();
    });
}

